#pragma once

#include <expected>
#include <string>
#include <string_view>

#include "image.hpp"

namespace visor::fontgen {

/// @brief Why a header could not be emitted. Recoverable: the caller reports
///        it, nothing terminates.
enum class EmitError {
    kEmptyName,         ///< The identifier is the empty string.
    kNameTooLong,       ///< Over the 63-character symbol limit.
    kInvalidCharacters, ///< Not [A-Za-z_][A-Za-z0-9_]*.
    kKeyword,           ///< A C++ keyword; a namespace of that name breaks compilation.
    kBadStorage,        ///< rows does not hold height * stride() bytes.
};

/// @brief One-line, user-facing wording for each emit failure.
[[nodiscard]] const char* describe(EmitError error) noexcept;

/**
 * @brief   Reports whether name is a valid namespace leaf for the generated
 *          header: an identifier that is not a C++ keyword, at most 63 chars.
 *
 * A valid identifier that happens to be a keyword would produce
 * "namespace visor::assets::int", which fails at the consumer's compile step,
 * far away from the tool run. The check lives here so the mistake dies at the
 * tool's own exit code instead.
 */
[[nodiscard]] bool valid_asset_name(std::string_view name) noexcept;

/**
 * @brief   Renders the image as a self-contained C++ header.
 *
 * The output exposes kWidth, kHeight, kStrideBytes and a kBits byte array in
 * namespace visor::assets::<name>, packed exactly like visor::canvas::Canvas
 * rows. The header comment records source_hint and the regenerate command so
 * a future reader never hand-edits generated bytes.
 *
 * @param[in] name        Namespace leaf, must satisfy valid_asset_name.
 * @param[in] source_hint Path of the source image, shown in comments only.
 * @param[in] image       The packed pixels to embed.
 */
[[nodiscard]] std::expected<std::string, EmitError>
emit_bitmap_header(std::string_view name, std::string_view source_hint, const MonoImage& image);

} // namespace visor::fontgen
